const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = { tr, en };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
  const dict = DICTIONARIES[locale];
  return (key, vars) => {
    const text = dict[key] ?? tr[key] ?? key;
    return vars ? text.replace(/\{(\w+)\}/g, (_m, name: string) => String(vars[name] ?? `{${name}}`)) : text;
  };
}

export function isLocale(v: string | undefined): v is Locale {
  return v === "tr" || v === "en";
}

/** Accept-Language başlığından tercih: Türkçe yoksa İngilizce. */
export function localeFromHeader(header: string | null | undefined): Locale {
  return /(^|,)\s*tr\b/i.test(header ?? "") ? "tr" : "en";
}

/** Yerelleştirilmiş biçimlendiriciler: para her dilde $ ile, süre ve sayı dile göre. */
export function formatters(locale: Locale) {
  const t = translator(locale);
  const numberLocale = locale === "tr" ? "tr-TR" : "en-US";
  return {
    usd(n: number): string {
      if (n === 0) return "$0";
      if (n < 0.01) return `$${n.toFixed(4)}`;
      if (n < 100) return `$${n.toFixed(2)}`;
      return `$${Math.round(n).toLocaleString("en-US")}`;
    },
    duration(seconds: number | undefined): string {
      if (seconds === undefined || !Number.isFinite(seconds)) return "—";
      const s = Math.round(seconds);
      if (s < 60) return `${s} ${t("unit.sec")}`;
      const m = Math.floor(s / 60);
      if (m < 60) return s % 60 ? `${m} ${t("unit.min")} ${s % 60} ${t("unit.sec")}` : `${m} ${t("unit.min")}`;
      const h = Math.floor(m / 60);
      return m % 60 ? `${h} ${t("unit.hour")} ${m % 60} ${t("unit.min")}` : `${h} ${t("unit.hour")}`;
    },
    number(n: number): string {
      return Math.round(n).toLocaleString(numberLocale);
    },
    date(iso: string): string {
      return new Date(iso).toLocaleString(numberLocale, { dateStyle: "medium", timeStyle: "short" });
    },
    day(iso: string): string {
      return new Date(iso).toLocaleDateString(numberLocale);
    },
    time(iso: string): string {
      return new Date(iso).toLocaleTimeString(numberLocale, { hour: "2-digit", minute: "2-digit", second: "2-digit" });
    },
    ago(iso: string, now = Date.now()): string {
      const s = Math.max(0, Math.round((now - Date.parse(iso)) / 1000));
      if (s < 5) return t("ago.now");
      if (s < 60) return t("ago.sec", { n: s });
      if (s < 3600) return t("ago.min", { n: Math.floor(s / 60) });
      if (s < 86400) return t("ago.hour", { n: Math.floor(s / 3600) });
      return t("ago.day", { n: Math.floor(s / 86400) });
    },
  };
}
export type Formatters = ReturnType<typeof formatters>;
