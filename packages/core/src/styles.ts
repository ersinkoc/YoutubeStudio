export const STYLE_PACK_IDS = STYLE_PACKS.map((p) => p.id);
export const stylePackOf = (id: string | undefined): StylePack | undefined => STYLE_PACKS.find((p) => p.id === id);

/** Paketin stil kitabı (sanat yönetmeni çıktısıyla aynı alanlar + paket kimliği ve tasarımcı notları). */
export function styleFromPack(pack: StylePack) {
  const { artStyle, promptPrefix, negativeRules, palette, lighting, lensLanguage, designNotes } = pack;
  return { artStyle, promptPrefix, negativeRules: [...negativeRules], palette: [...palette], lighting, lensLanguage, pack: pack.id, designNotes };
}

